/**
 * ⚠️ **مصدرٌ واحد لنطاق كوكي الجلسة — لا ثلاثة.**
 *
 * كان المتصفحُ والخادمُ والوسيط يفحص كلٌّ منها `NODE_ENV === 'production'`
 * بنفسه. و`NODE_ENV` يساوي `production` في **كل** نشرٍ على Vercel — بما
 * فيه المعاينات. فيُلحَق `domain=.ghiras-edu.com` على مضيفٍ اسمه
 * `*.vercel.app`، فلا يطابق، فيرفض المتصفح الكوكي.
 *
 * و`@supabase/ssr` لا يخزّن الجلسة إلا في الكوكي — لا `localStorage` ولا
 * ذاكرة. فتضيع الجلسة **بعد نجاح المصادقة مباشرة**، فتُحجب قراءةُ الملف
 * بالحماية، فترجع صفر صفوف (`PGRST116`)، فيُقال لحسابٍ سليم:
 * «الحساب غير مهيأ بعد». عطبٌ تقنيّ يخرج في صورة تهمة.
 *
 * ⚠️ وغيابُ المتغيّر يعني **ألّا تُرسَل خاصية `domain` أصلًا** — لا
 * `domain: ''`، فالنصّ الفارغ يُفسَّر نطاقاً فاسداً لا غياباً للنطاق.
 *
 * ⚠️ ولا يُنقل هذا إلى ملفٍ يحمل `'use client'`: استيراده من الخادم
 * حينئذٍ يكسره، وTypeScript لا يمسك ذلك.
 *
 * ⚠️ ويُضمَّن `NEXT_PUBLIC_*` وقت البناء لا وقت التشغيل — فتغييره في
 * Vercel يوجب إعادة بناء، ويجب ضبطه **قبل** أول نشر.
 */
const raw = process.env.NEXT_PUBLIC_COOKIE_DOMAIN;

/** `{ domain }` إن وُجد نطاق، و`{}` إن لم يوجد. */
export const cookieDomainOption: { domain?: string } =
  raw && raw.trim() ? { domain: raw.trim() } : {};
