export type TajweedRule =
  // ── النون الساكنة والتنوين ──
  /** إظهار — نون ساكنة أو تنوين قبل حرف حلق. */
  | 'idhhar'
  /** إدغام بغنّة — قبل (ي ن م و). */
  | 'idgham_ghunnah'
  /** إدغام بغير غنّة — قبل (ل ر). */
  | 'idgham_no_ghunnah'
  /** إقلاب — قبل الباء، ويُرسم بميمٍ صغيرة. */
  | 'iqlab'
  /** إخفاء — قبل الخمسة عشر الباقية. */
  | 'ikhfa'
  // ── الميم الساكنة ──
  /** إخفاء شفوي — ميم ساكنة قبل باء. */
  | 'ikhfa_shafawi'
  /** إدغام شفوي — ميم ساكنة قبل ميم. */
  | 'idgham_shafawi'
  /** إظهار شفوي — ميم ساكنة قبل بقية الحروف. */
  | 'idhhar_shafawi'
  // ── أحكام عامة ──
  /** غنّة — نون أو ميم مشدّدة. */
  | 'ghunnah'
  /** قلقلة — (ق ط ب ج د) ساكنة. */
  | 'qalqalah'
  /** همزة وصل — تسقط في الوصل. */
  | 'hamzat_wasl'
  /** لام شمسية — لا تُنطق ويُشدَّد ما بعدها. */
  | 'lam_shamsiyyah';

