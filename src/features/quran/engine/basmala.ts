/**
 * فصل البسملة الافتتاحية عن الآية الأولى — **طبقة عرض فقط**.
 *
 * ⚠️ لا يُعدَّل النص المخزَّن. `corpus/quran-uthmani.txt` يبقى كما نزل من
 * Tanzil حرفًا بحرف، وبصمته لا تتغيّر. هذه الدالة تُرجع نسخة للعرض،
 * وتُعيد البسملة نفسها **بحروفها كما وردت** لتُرسم في سطرها المستقل —
 * فلا نكتب نحن نصًا قرآنيًا ولا نعيد تشكيله، بل ننقل ما هو مخزَّن.
 *
 * ── لماذا نحتاجها ──
 * صيغة Tanzil تُلحق البسملة بنص الآية الأولى في السور التي تفتتح بها.
 * فتظهر «بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ قُلْ هُوَ ٱللَّهُ أَحَدٌ ①»
 * وكأن البسملة جزء من الآية ورقمها يعود عليها، وهذا غير صحيح.
 *
 * ── القاعدة ──
 * لا تحتوي هذه الشيفرة رقم سورة واحدًا مكتوبًا يدويًا. الاستثناءات
 * تنشأ من النص نفسه:
 *
 *   ١) لا تُفصل إلا إذا كان المقطع يبدأ من **الآية الأولى**. فمن فتح
 *      مقطعًا من وسط السورة لا تُقحم عليه بسملة ليست في موضعها.
 *
 *   ٢) تُطابَق أول أربع كلمات بعد التطبيع. والتطبيع ضروري لا تجميلي:
 *      في التين والقدر تُرسم الباء بشدّة (بِّسْمِ) لأن السورة قبلهما
 *      تنتهي بباء فيُدغم عند الوصل. صورتان مختلفتان لبسملة واحدة،
 *      والمطابقة الحرفية كانت ستُسقط إحداهما.
 *
 *   ٣) لا تُفصل إن لم يبقَ بعدها نص. وهذا هو ما يستثني **الفاتحة**
 *      وحدها: البسملة فيها هي الآية الأولى بعدّ حفص ورقمها ١ حقّها،
 *      فنزعها يُفرغ الآية ويُسقط آية من السورة. الاستثناء ينشأ من
 *      بنية النص لا من شرط نكتبه على السورة رقم ١.
 *
 *   ٤) سورة التوبة تسقط تلقائيًا: أول آية فيها «بَرَآءَةٌ…» فلا تطابق.
 *
 *   ٥) ٢٧:٣٠ فيها البسملة لكن في آخر الآية لا أولها ورقمها ٣٠ لا ١،
 *      فتخرج بالشرطين الأول والثاني معًا.
 *
 * النتيجة على المصحف كاملًا: تُفصل في ١١٣ سورة، ولا تُفصل في التوبة،
 * ولا في الفاتحة. مُتحقَّق منه في `scripts/quran/test-basmala.mjs`.
 */

import type { Ayah } from '../types';
import { normalizeForComparison, splitWords } from './normalize.mjs';

/** البسملة مطبَّعة — للمطابقة فقط، ولا تُعرض للمستخدم أبدًا. */
const BASMALA_NORMALIZED = 'بسم الله الرحمن الرحيم';

/** البسملة أربع كلمات: بسم · الله · الرحمن · الرحيم. */
const BASMALA_WORDS = 4;

export type BasmalaSplit = {
  /** نص البسملة كما ورد في المصحف، أو null إن لم تكن هذه بداية سورة. */
  basmala: string | null;
  /**
   * رقم الآية الذي يُعرض مع البسملة، أو null.
   *
   * ليس له قيمة إلا في **الفاتحة**: البسملة فيها آية بعدّ حفص ورقمها ١
   * حقّها، وهكذا تُرسم في المصحف المطبوع — في سطرها المستقل ومعها
   * علامة الآية. أما في سائر السور فالبسملة افتتاحية لا آية معدودة،
   * فلا يجاورها رقم البتة.
   */
  basmalaAyahNumber: number | null;
  /** الآيات للعرض؛ الأولى بلا البسملة إن فُصلت. */
  ayahs: Ayah[];
};

/**
 * يفصل البسملة الافتتاحية إن وُجدت.
 *
 * @param ayahs آيات المقطع مرتّبة، أولها أول ما يُعرض
 */
export function splitOpeningBasmala(ayahs: Ayah[]): BasmalaSplit {
  const none: BasmalaSplit = { basmala: null, basmalaAyahNumber: null, ayahs };
  const first = ayahs[0];

  // ١) المقطع لا يبدأ من أول السورة
  if (!first || first.ayah !== 1) return none;

  const words = splitWords(first.text_uthmani);

  // ٢) أول أربع كلمات ليست البسملة
  const head = words.slice(0, BASMALA_WORDS).join(' ');
  if (words.length < BASMALA_WORDS || normalizeForComparison(head) !== BASMALA_NORMALIZED)
    return none;

  const rest = words.slice(BASMALA_WORDS).join(' ');

  // ٣) لا يبقى بعدها نص — البسملة هي الآية الأولى نفسها (الفاتحة).
  //    تُرفع إلى سطرها المستقل ومعها رقمها، ولا تبقى في تدفّق الآيات
  //    حتى لا تُعرض مرتين. آية لم تُنقص ولا حرف تغيّر.
  if (!rest)
    return {
      basmala: first.text_uthmani,
      basmalaAyahNumber: first.ayah,
      ayahs: ayahs.slice(1),
    };

  // ٤) بسملة افتتاحية: تُفصل بلا رقم، ورقم الآية يبقى لصاحبه
  return {
    // البسملة بحروفها كما وردت، لا صورة نكتبها نحن
    basmala: head,
    basmalaAyahNumber: null,
    ayahs: [{ ...first, text_uthmani: rest }, ...ayahs.slice(1)],
  };
}

/**
 * هل يفتتح هذا المقطع ببسملة **ليست آية معدودة**؟
 *
 * يستعمله المشغّل ليقرّر هل يسبق التلاوةَ ملفُّ بسملة أم لا. وهو نفس
 * القرار الذي يتخذه العرض، مشتقًّا من نفس الدالة — فلا يمكن أن تظهر
 * البسملة مكتوبة ولا تُتلى، ولا أن تُتلى ولا تُكتب.
 *
 * يُرجع false في الفاتحة عن قصد: البسملة فيها آية لها ملفها الصوتي
 * ضمن الترقيم، فيكفي أن تُتلى في موضعها من قائمة التشغيل.
 */
export function opensWithSpokenBasmala(ayahs: Ayah[]): boolean {
  const { basmala, basmalaAyahNumber } = splitOpeningBasmala(ayahs);
  return basmala !== null && basmalaAyahNumber === null;
}

/**
 * الآيات بلا بسملة افتتاحية — للأنشطة والتوليد، لا للعرض.
 *
 * ⚠️ يفحص **كل آية** لا رأس القائمة وحده. `splitOpeningBasmala` تفصل
 * من الأولى فقط، وهو كافٍ للمقطع لأنه من سورة واحدة. أما صفحة المصحف
 * فقد تبدأ فيها سورة في وسطها، فتبقى بسملتها ملتصقة بآيتها ثم تتسرّب
 * إلى سؤال أو خيار، أو تُخفى منها كلمة في «الكلمة المفقودة».
 *
 * وهذا خطأ وقع مرة من قبل في أول السورة وأُصلح، فعاد يهدّد من باب
 * الصفحة. فمُنِع في دالة واحدة يستعملها كل من يولّد سؤالًا.
 *
 * والفاتحة تُسقَط آيتها الأولى عن قصد: بسملتها آية معدودة، فلا يبقى
 * منها نصّ بعد الفصل.
 */
export function ayahsForActivities(ayahs: Ayah[]): Ayah[] {
  const out: Ayah[] = [];
  for (const a of ayahs) {
    const rest = splitOpeningBasmala([a]).ayahs[0];
    if (rest) out.push(rest);
  }
  return out;
}
