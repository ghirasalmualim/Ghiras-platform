/**
 * محرك الحفظ الخفي — إخفاء الكلمات تدريجيًا.
 *
 * الفكرة: يبدأ الطالب بالنص كاملًا أمامه، ثم يُخفى منه شيء فشيء حتى
 * يتلوه من ذاكرته. الذاكرة تُسند أولًا ثم يُسحب السند رويدًا.
 *
 * ⚠️ القيد الحاكم — الكلمة المخفية **تبقى في موضعها الأصلي**:
 *   • لا يُعاد ترتيب الكلمات.
 *   • لا تُقطَّع الآية إلى بطاقات.
 *   • لا يوجد — ولن يوجد — نشاط «رتّب الآية».
 *
 * السبب: خلط ترتيب كلام الله لأجل لعبة لا يجوز، ولو كانت نية اللعبة
 * التعليم. فكل ما نفعله هنا إخفاء، والموضع محفوظ دائمًا.
 *
 * ⚠️ ولا نخفي إلا **العرض**. النص المرجعي لا يُمسّ: الدوال تُرجع أقنعة
 * (أي الكلمات المخفية) ولا تعيد كتابة النص ولا تُنتج نصًا ناقصًا.
 *
 * دوال نقية وحتمية: نفس المدخلات تعطي نفس الإخفاء دائمًا، فلا تقفز
 * الكلمات أمام الطالب كلما أُعيد رسم الشاشة.
 */

/** مستويات الإخفاء: ٠ = النص كامل … ٥ = كل الكلمات مخفية. */
import { seededRandom } from './random.mjs';

export const HIDE_LEVELS = [0, 1, 2, 3, 4, 5] as const;
export type HideLevel = (typeof HIDE_LEVELS)[number];

/** نسبة الكلمات المخفية عند كل مستوى. */
const HIDDEN_RATIO: Record<HideLevel, number> = {
  0: 0,
  1: 0.2,
  2: 0.4,
  3: 0.6,
  4: 0.8,
  5: 1,
};

export const LEVEL_LABEL: Record<HideLevel, string> = {
  0: "النص كامل",
  1: "إخفاء خفيف",
  2: "إخفاء رُبع",
  3: "إخفاء نصف",
  4: "إخفاء معظم النص",
  5: "من الذاكرة",
};

/**
 * يختار مواضع الكلمات المخفية في آية.
 *
 * @param wordCount عدد كلمات الآية
 * @param level     مستوى الإخفاء
 * @param seed      بذرة ثابتة (نمرّر رقم الآية) لثبات الاختيار
 * @returns مجموعة مواضع تبدأ من ٠ (فهرس داخل مصفوفة الكلمات)
 *
 * الإخفاء **تراكمي**: ما يُخفى في المستوى ٢ يبقى مخفيًا في ٣. فيشعر
 * الطالب أن السند يُسحب تدريجيًا، لا أن الكلمات تتبادل الظهور.
 */
export function hiddenIndices(
  wordCount: number,
  level: HideLevel,
  seed: number
): Set<number> {
  if (level === 0 || wordCount === 0) return new Set();
  if (level === 5) return new Set(Array.from({ length: wordCount }, (_, i) => i));

  // ترتيب ثابت للكلمات، ثم نأخذ منه بادئة بطول النسبة المطلوبة.
  // البادئة هي سرّ التراكم: كل مستوى يأخذ ما أخذه سابقه وزيادة.
  const order = Array.from({ length: wordCount }, (_, i) => i);
  const rand = seededRandom(seed);
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }

  const n = Math.max(1, Math.round(wordCount * HIDDEN_RATIO[level]));
  return new Set(order.slice(0, n));
}

/**
 * ملاحظة: لا توجد هنا دالة تُنتج «شكلًا نائبًا» للكلمة المخفية، وهذا
 * مقصود.
 *
 * النائب المصنوع (نقاط أو شرطات) يقارب عرض الكلمة ولا يطابقه، فيزحف
 * السطر قليلًا مع كل مستوى إخفاء. واستقرار الشكل البصري ليس تفصيلًا
 * تجميليًا في الحفظ: الحافظ يتذكّر موضع الكلمة في الصفحة، فإذا تحرّك
 * النص تحته ضاع هذا السند.
 *
 * فالإخفاء يجري في العرض: الكلمة تبقى في مكانها بحرفها وحجمها ويُجعل
 * لونها شفافًا مع خلفية وخط سفلي (انظر `.hidden-word` في globals.css).
 * فيبقى العرض مطابقًا للأصل مطابقة تامة لا مقاربة، ولا يتزحزح حرف.
 */
