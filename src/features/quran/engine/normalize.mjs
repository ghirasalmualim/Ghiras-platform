/**
 * تطبيع النص العربي للمقارنة والبحث — دوال نقية بلا أي أثر جانبي.
 *
 * ⚠️ قاعدة حاكمة: هذه الدوال **لا تُنتج نصًا قرآنيًا**. مخرجاتها صورة
 * مشتقّة تُستخدم للمقارنة والبحث فقط، لا تُعرض للمستخدم قط ولا تُكتب
 * فوق `text_uthmani`. النص العثماني هو المرجع الوحيد ويبقى كما ورد من
 * المصدر حرفيًا.
 *
 * سبب وجودها: مخرجات التعرّف على الكلام تأتي بلا تشكيل وبأشكال حروف
 * مختلفة. فلو قارنّاها بالنص العثماني كما هو، لظهر الطالب المتقن مخطئًا
 * لأن المفرّغ كتب «إنا» والنص «إِنَّا». فنُطبّع **الطرفين** بنفس القواعد
 * ثم نقارن.
 *
 * الصيغة .mjs مقصودة: هذا الملف يستورده سكربت الاستيراد (Node) وتطبيق
 * Next.js معًا. نسخة واحدة لا نسختان — لأن اختلاف القاعدتين يومًا ما
 * يجعل التلاوة الصحيحة تُحسب خطأ بلا سبب ظاهر.
 *
 * القواعد مطبَّقة بالترتيب، وكل واحدة موثّقة عمدًا لتكون قابلة لمراجعة مختص.
 */

/** التشكيل وعلامات الضبط: فتحة…سكون، والألف الخنجرية، وعلامات الوقف القرآنية. */
const DIACRITICS = /[ً-ْٰ۟۠ٓ-ٕٖ-ٟۖ-ۭ]/g;

/** التطويل (الكشيدة) — زخرفة خطية لا تحمل معنى. */
const TATWEEL = /ـ/g;

/** محارف غير مرئية قد ترد من لوحات المفاتيح أو من التفريغ. */
const INVISIBLE = /[​-‏؜﻿]/g;

/**
 * توحيد أشكال الحروف التي تُكتب بصور متعددة لنفس النطق.
 * توحيد **للمقارنة** فقط، ولا يصح إظهاره كنص قرآني.
 * @type {Array<[RegExp, string]>}
 */
const LETTER_MAP = [
  // الألف بأشكالها: أ إ آ ٱ ٲ ٳ → ا
  [/[أإآٱٲٳ]/g, "ا"],
  // الألف المقصورة → ياء (يوحّد «الذى» و«الذي»)
  [/ى/g, "ي"],
  // التاء المربوطة → هاء (يوحّد «رحمة» و«رحمه»)
  [/ة/g, "ه"],
  // الهمزة على واو أو ياء → همزة مفردة
  [/[ؤئ]/g, "ء"],
];

/**
 * يُطبّع كلمة أو نصًا للمقارنة.
 * يُستدعى على **كلا الطرفين** دائمًا: النص المرجعي ومخرجات التفريغ.
 * @param {string} input
 * @returns {string}
 */
export function normalizeForComparison(input) {
  let s = input.normalize("NFC");
  s = s.replace(INVISIBLE, "");
  s = s.replace(DIACRITICS, "");
  s = s.replace(TATWEEL, "");
  for (const [re, to] of LETTER_MAP) s = s.replace(re, to);
  return s.replace(/\s+/g, " ").trim();
}

/**
 * يقطّع نصًا إلى كلمات مع الحفاظ على ترتيبها الأصلي.
 * الترتيب جزء من البيانات ولا يجوز خلطه — لا يوجد في المنصة أي نشاط
 * يعيد ترتيب كلمات الآية، وهذا قرار مقصود لا سهو.
 * @param {string} text
 * @returns {string[]}
 */
export function splitWords(text) {
  return text.split(/\s+/).filter(Boolean);
}
