/**
 * الأرقام العربية الشرقية — أنسب لسياق المصحف.
 *
 * ── لماذا هنا لا في مكوّن ──
 * كانت ساكنة في `ResumeCard.tsx` وهو ملف يبدأ بـ`'use client'`. وNext.js
 * يحوّل **كل** صادرات ملف العميل إلى مراجع لا دوال، فمن استوردها في
 * مكوّن خادمي وجد مرجعًا ونادَاه فانفجرت الصفحة وقت التشغيل.
 *
 * ⚠️ وTypeScript لا يمسك هذا: الأنواع سليمة تمامًا، والفرق يظهر بعد
 * الحزم لا قبله. فمكان الدالة المشتركة ملفٌ محايد لا مكوّن عميل.
 */
export function toArabic(n: number): string {
  return String(n).replace(/\d/g, (d) => '٠١٢٣٤٥٦٧٨٩'[Number(d)]);
}

/**
 * تمييز العدد في العربية.
 *
 * «٣ آية» غلطٌ يقرؤه كل من يفتح صفحة، والعربية تميّز المفرد والمثنى
 * وجمع القلّة والكثرة. سطرٌ واحد يكفي، وتركه يجعل الشاشة تبدو مترجمة
 * لا مكتوبة بالعربية.
 */
export function countAyahs(n: number): string {
  if (n === 1) return 'آية واحدة';
  if (n === 2) return 'آيتان';
  if (n <= 10) return `${toArabic(n)} آيات`;
  return `${toArabic(n)} آية`;
}
