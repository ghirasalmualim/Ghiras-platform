/**
 * موضع القراءة — قواعد «تابع من حيث وقفت».
 *
 * ═══ العطب الذي وُلد منه هذا الملف ═══
 * كان فتحُ شاشة الدراسة يكتب الموضع إلى بداية المقطع بلا شرط —
 * فمن بلغت البقرة ٢٢ ثم دخلتها من أي بابٍ يبدأ بالآية ١ (تصفحًا،
 * أو «ابدأ خطة اليوم» التي تتجدد كل صباح) انسحق موضعُها وعاد ١.
 * وبدا الأمر مرتبطًا بمنتصف الليل وهو بريء — لا مفتاحَ يومٍ في
 * مسار الموضع كله.
 *
 * ═══ القاعدة المعتمدة ═══
 * **PAGE OPEN ≠ READING PROGRESS.**
 * فتحُ صفحةٍ أو رابطٍ أو درسٍ لا يغيّر الموضع أبدًا — الموضع يتغير
 * فقط بنيّة قراءةٍ صريحة:
 *   ١) «🔊 استمع من هنا» على آية — يسجلها.
 *   ٢) «✅ انتهيت هنا» — force: له وحده حقُّ الرجوع للخلف
 *      وتغيير السورة قصدًا.
 * ولا يوجد «سورة مختلفة = مقصود تلقائيًا»: مصدرُ الحدث هو الحكم،
 * لا وجهتُه.
 *
 * ═══ عقد الاستدعاء (يحرسه اختبار نصي) ═══
 * ⚠️ `shouldSaveResume` لا تُستدعى إلا من تفاعل قراءةٍ حقيقي أو
 * force — **ولا تُستدعى من mount إطلاقًا**: الـmount لا ينادي الحفظ
 * أصلًا، لا أنه ينادي ويُرفض.
 *
 * ═══ ثلاثة مفاهيم لا تُخلط ═══
 * موضعُ القراءة (هنا) ≠ موضعُ الحفظ ≠ التقدّمُ الموثوق من
 * المراجعة. هذا الملف يمسّ الأول وحده.
 */

export type ResumePos = {
  surah: number;
  ayah: number;
  /** قد يغيب في سجلات المتصفح القديمة — يُعامل بتحفظ لا بتخمين. */
  updated_at?: string | null;
};

/**
 * هل يُحفظ الموضع الجديد؟
 *
 *   force                    → نعم (نية صريحة — رجوعًا أو سورةً أخرى)
 *   لا موضع محفوظ            → نعم (أول تفاعل)
 *   سورة مختلفة              → نعم (المستدعي تفاعلٌ بالعقد أعلاه)
 *   نفس السورة وآية أبعد     → نعم
 *   نفس السورة وآية أقرب/هي  → لا — القراءة لا تمشي للخلف بغير قصد
 */
export function shouldSaveResume(
  stored: ResumePos | null,
  next: { surah: number; ayah: number },
  force = false
): boolean {
  if (force) return true;
  if (!stored) return true;
  if (next.surah !== stored.surah) return true;
  return next.ayah > stored.ayah;
}

/**
 * أيّ الموضعين أحدث — متصفحٌ أم قاعدة؟ (لمن سجّلت دخولها)
 *
 * ⚠️ **لا ادعاء دقةٍ لا نملكها**: الطابعان كلاهما من ساعة جهاز
 * العميل أصلًا (القاعدة تخزّن ما أرسله المتصفح)، فالمقارنة صالحة
 * لجهازٍ واحد، وبين جهازين انحرافُ دقائق قد يقلبها. والثمن مقبول:
 * أسوأ الحالات اختيارُ موضعِ قراءةٍ صحيحٍ آخر لا فسادُ بيانات.
 *
 * القاعدة المحافظة الموثقة:
 *   كلاهما بطابع → الأحدث طابعًا (وعند التساوي: القاعدة).
 *   سجل متصفح قديم بلا طابع → **القاعدة تغلب** إن وُجدت — لا نخمّن
 *   عمرَ مجهول؛ وإن لم توجد قاعدة فالمحلي خيرٌ من لا شيء.
 */
export function newerResume(
  local: ResumePos | null,
  db: ResumePos | null
): { pos: ResumePos | null; source: 'local' | 'db' | 'none' } {
  if (!local && !db) return { pos: null, source: 'none' };
  if (!local) return { pos: db, source: 'db' };
  if (!db) return { pos: local, source: 'local' };
  if (!local.updated_at) return { pos: db, source: 'db' }; // legacy: لا تخمين
  if (!db.updated_at) return { pos: local, source: 'local' };
  return local.updated_at > db.updated_at
    ? { pos: local, source: 'local' }
    : { pos: db, source: 'db' };
}
