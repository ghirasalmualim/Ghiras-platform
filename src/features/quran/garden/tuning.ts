import type { DropReason, RewardKey } from './types';

/**
 * أرقام «حديقتي» — كلها هنا، ولا رقم منها مبعثرٌ في الكود.
 *
 * ── لماذا ملف مستقل ──
 * هذه قيمُ إيقاعٍ لا قيمُ صواب: كم يومًا حتى تكتمل نبتة، وكم قطرةً في
 * اليوم. وجوابها لا يأتي من المنطق بل من أطفال يجرّبون. فتُجمع هنا
 * لتُعدَّل في مكان واحد بعد التجربة، لا أن تُلاحَق في عشرة ملفات.
 *
 * ⚠️ **قيم ابتدائية لم تُجرَّب على طفل واحد بعد.** ستتغيّر، وهذا
 * متوقَّع لا عيب.
 *
 * ── القاعدة الحاكمة ──
 * ⚠️ لا رقم هنا يُنقص شيئًا. لا ذبول، ولا خصم، ولا انتهاء صلاحية.
 * الحديقة تُشجّع على الرجوع ولا تعاقب على الغياب — ومن رجع بعد شهر
 * وجد نبتته كما تركها بالضبط.
 */

export type GardenTuning = {
  /** كم قطرةً تُنقل النبتة من كل مرحلة إلى التي بعدها. */
  dropsPerStage: readonly number[];
  /** كم قطرةً يستحقّ كل سبب. */
  dropValue: Readonly<Record<DropReason, number>>;
  /** سقف القطرات في اليوم الواحد. */
  maxDropsPerDay: number;
  /** أقصى ما يُحتفظ به من قطرات غير مستعملة. */
  maxHeldDrops: number;
  /** عدد المساحات في الحديقة. */
  slots: number;
  /** عتبات فتح الزينة بعدد النباتات المكتملة. */
  rewardsByPlants: Readonly<Record<number, RewardKey>>;
  /** عتبات فتح الزينة بعدد أيام العناية. */
  rewardsByCareDays: Readonly<Record<number, RewardKey>>;
};

